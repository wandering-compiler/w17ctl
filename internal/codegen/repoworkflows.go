package codegen

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	codegenpb "github.com/wandering-compiler/sdk/go/pb/w17compiler"
)

// A project in a directory of its repository (w17/infra.yaml ci.project_dir)
// gets its workflows rendered with a `# w17 project dir: <dir>` line. GitHub
// reads .github/workflows at the repository's root only, so those files go
// there rather than under the project: the one place codegen writes outside
// the project root, and only for a file the infra target rendered, naming the
// directory the project really is in.

// workflowsDir is where the infra target renders a project's workflows.
const workflowsDir = ".github/workflows/"

// projectDirLineRe is the line swarm.ProjectDirLine opens.
var projectDirLineRe = regexp.MustCompile(`(?m)^# w17 project dir: (\S+)$`)

// workflowProjectDir is the directory a rendered workflow names, "" for none
// (a project at its repository's root). The line sits in the file's head.
func workflowProjectDir(contents []byte) string {
	head := contents
	if len(head) > 4096 {
		head = head[:4096]
	}
	if !infraMarkerRe.Match(head) {
		return ""
	}
	if m := projectDirLineRe.FindSubmatch(head); m != nil {
		return string(m[1])
	}
	return ""
}

// repoWorkflows are the workflows of a project in a directory of its
// repository: written to repoRoot/.github/workflows.
type repoWorkflows struct {
	repoRoot string
	dir      string
	files    []*codegenpb.GeneratedFile
}

// findRepoRoot is the nearest directory at or above root holding .git (a
// directory, or a worktree's file); "" when there is none.
func findRepoRoot(root string) string {
	abs, err := filepath.Abs(root)
	if err != nil {
		return ""
	}
	for d := abs; ; d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, ".git")); err == nil {
			return d
		}
		if filepath.Dir(d) == d {
			return ""
		}
	}
}

// splitRepoWorkflows takes the workflows that name a project directory out of
// writes. Each must name the directory the project really is in, relative to
// the repository's root: a project moved since its ci.project_dir was set
// would otherwise get workflows that build another directory.
func splitRepoWorkflows(root string, writes []*codegenpb.GeneratedFile) ([]*codegenpb.GeneratedFile, *repoWorkflows, error) {
	var rest []*codegenpb.GeneratedFile
	var rw *repoWorkflows
	for _, f := range writes {
		rel := filepath.ToSlash(f.GetRelativePath())
		dir := ""
		if strings.HasPrefix(rel, workflowsDir) && !strings.Contains(strings.TrimPrefix(rel, workflowsDir), "/") {
			dir = workflowProjectDir(f.GetContents())
		}
		if dir == "" {
			rest = append(rest, f)
			continue
		}
		if rw == nil {
			repoRoot := findRepoRoot(root)
			if repoRoot == "" {
				return nil, nil, fmt.Errorf("codegen: the workflows are for a project in %s/ of its repository (w17/infra.yaml ci.project_dir), and no git repository holds %s — GitHub reads them from the repository's root", dir, root)
			}
			abs, err := filepath.Abs(root)
			if err != nil {
				return nil, nil, err
			}
			at, err := filepath.Rel(repoRoot, abs)
			if err != nil || filepath.ToSlash(at) != dir {
				return nil, nil, fmt.Errorf("codegen: w17/infra.yaml ci.project_dir is %s, and the project is in %s of its repository (%s) — `w17ctl infra set ci.project_dir=%s`", dir, describeAt(at), repoRoot, filepath.ToSlash(at))
			}
			rw = &repoWorkflows{repoRoot: repoRoot, dir: dir}
		} else if dir != rw.dir {
			return nil, nil, fmt.Errorf("codegen: the workflows name two project directories (%s, %s)", rw.dir, dir)
		}
		rw.files = append(rw.files, f)
	}
	return rest, rw, nil
}

func describeAt(at string) string {
	if at == "." {
		return "the root"
	}
	return filepath.ToSlash(at) + "/"
}

// write lays the workflows down in the repository's .github/workflows, then
// removes the ones an earlier run wrote for this project and this run did
// not (an environment removed, CI removed). A file there without the infra
// target's banner is a person's and is never replaced; a workflow naming
// another directory is another project's and is never touched.
func (rw *repoWorkflows) write(stdout io.Writer) error {
	dst := filepath.Join(rw.repoRoot, filepath.FromSlash(workflowsDir))
	written := map[string]bool{}
	for _, f := range rw.files {
		name := strings.TrimPrefix(filepath.ToSlash(f.GetRelativePath()), workflowsDir)
		target := filepath.Join(dst, name)
		if cur, err := os.ReadFile(target); err == nil { // #nosec G304 -- a name under the repository's .github/workflows
			if !hasInfraMarker(target) {
				return fmt.Errorf("codegen: %s is yours (no `Code generated by w17 (infra target …)` banner) — rename it, or delete it to let codegen write the workflow", target)
			}
			if d := workflowProjectDir(cur); d != rw.dir {
				return fmt.Errorf("codegen: %s is the workflow of the project in %s — two projects of one repository render workflows of one name", target, describeProjectDir(d))
			}
		}
		if err := os.MkdirAll(dst, 0o755); err != nil {
			return err
		}
		if cur, err := os.ReadFile(target); err != nil || !bytes.Equal(cur, f.GetContents()) { // #nosec G304 -- as above
			if err := os.WriteFile(target, f.GetContents(), 0o644); err != nil { // #nosec G306 -- a workflow, read by git and GitHub
				return err
			}
		}
		written[name] = true
	}
	return pruneRepoWorkflows(dst, rw.dir, written, stdout)
}

func describeProjectDir(d string) string {
	if d == "" {
		return "the repository's root"
	}
	return d + "/"
}

// pruneRepoWorkflows removes from dst the infra-rendered workflows of the
// project in dir that written does not name.
func pruneRepoWorkflows(dst, dir string, written map[string]bool, stdout io.Writer) error {
	entries, err := os.ReadDir(dst)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, e := range entries {
		if e.IsDir() || written[e.Name()] {
			continue
		}
		p := filepath.Join(dst, e.Name())
		body, err := os.ReadFile(p) // #nosec G304 -- a file of the repository's .github/workflows
		if err != nil || workflowProjectDir(body) != dir {
			continue
		}
		if err := os.Remove(p); err != nil {
			return err
		}
		fmt.Fprintf(stdout, "codegen: pruned %s (a workflow of this project no longer rendered)\n", p)
	}
	return nil
}

// pruneOwnRepoWorkflows is the prune for a run that rendered no workflow of a
// project in a directory: the ones an earlier run wrote for it go (CI
// removed, or ci.project_dir cleared).
func pruneOwnRepoWorkflows(root string, stdout io.Writer) error {
	repoRoot := findRepoRoot(root)
	if repoRoot == "" {
		return nil
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	at, err := filepath.Rel(repoRoot, abs)
	if err != nil || at == "." {
		return nil
	}
	return pruneRepoWorkflows(filepath.Join(repoRoot, filepath.FromSlash(workflowsDir)), filepath.ToSlash(at), nil, stdout)
}
